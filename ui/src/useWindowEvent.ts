import { useEffect, useLayoutEffect, useRef } from "react";

/**
 * **窓の出来事を、張り替えずに聞く**（2026-09-08）。
 *
 * ## なぜ要るのか——**張り替えると、その1回が落ちる**
 *
 * DOM の決まりで、**配信の最中に外された受け口は呼ばれない**（配信中に足した物も
 * 呼ばれない）。そして**受け口と受け口の間で JS の山が空になる**ので、
 * **そこでマイクロタスクが走り、React が描き直す**。
 *
 * pictkura で実際に起きた形（2026-09-08・win が Windows 実機で捕まえ、mac でも前後を測った）:
 *
 * 1. ビューアは**1.8 秒で操作系を隠す**。隠すための `wake` が、窓の `keydown` を
 *    **ウィザードや設定より先に**聞いている
 * 2. 休んでいるときに `Esc` を押すと、`wake` が `setViewerIdle(false)` を呼ぶ
 *    ——**休んでいるときだけ値が実際に変わる**ので、ここで描き直しが走る
 * 3. ウィザードや設定の受け口は、**`onClose` が毎回作り直される矢印**なので
 *    効果が回り直し、**外されて付け直される**
 * 4. **その `Esc` は、もう外れた受け口には届かない**——利用者には
 *    「**1回目の Esc が効かない**」に見える。**2回目は効く**
 *
 * **測った**（各3回・`.viewer` に `idle` が付いたことを確かめてから1回押す）:
 * 直す前は**ウィザード 0/3・設定 0/3・右クリックのメニュー 0/3**、
 * **関所だけ 3/3**（あれの `Esc` はビューア自身の受け口の中で、依存が休止で変わらない）。
 *
 * ## 直し方——**受け口の身元を固定する**
 *
 * 中身を ref に置き、**窓へ渡す関数は `active` が変わるときだけ作り直す**。
 *
 * **呼ぶ側で `useCallback` を並べる手もある**が、**あちらは黙って壊れる**
 * ——`onClose={() => ...}` を1つ書き足した日に、また落ちるようになる。
 */
export function useWindowEvent<K extends keyof WindowEventMap>(
  type: K,
  active: boolean,
  handler: (e: WindowEventMap[K]) => void,
): void {
  const ref = useRef(handler);
  // **レンダー中に ref を書き換えない**（捨てられる描き直しの値が残りうる）。
  // `useLayoutEffect` は描画の確定後・**受動の効果より先**に走る
  useLayoutEffect(() => {
    ref.current = handler;
  });
  useEffect(() => {
    if (!active) return;
    const on = (e: WindowEventMap[K]) => ref.current(e);
    window.addEventListener(type, on as EventListener);
    return () => window.removeEventListener(type, on as EventListener);
  }, [type, active]);
}

/**
 * 直近で「答えた」キーの出来事。**同じ押しに2つが答えないため**だけに在る。
 *
 * **配信が終わったら手放す**（下）。**握り続けると、`target` から外れた木が丸ごと残る**
 * ——関所は「戻る」に焦点を当てるので、**あの `Esc` の `target` は関所のボタン**であり、
 * 親をたどると**サムネイル最大200枚を含む幕ごと**である（あそこは約 140 MiB を見込む場所）。
 */
let answered: KeyboardEvent | null = null;

/**
 * **この押しに答えてよいか**（答えるなら `true` を返し、以後は同じ押しに答えられない）。
 *
 * **`Esc` の1押しで2つ閉じるのを、順番に頼らずに止める**ための道具である。
 *
 * **効くのは、これを通る受け口どうしの間だけである。** いまは4つ——
 * 関所・設定・ウィザード・右クリックのメニュー。**通っていない `Esc` の受け口が4つ在る**
 * （ビューアを閉じる／ショートカット一覧／選択の解除／検索欄）。
 * **いまはそれらと幕が同時に効くことが無い**ので競らないが、
 * **「1回の押しは必ず1つ」ではない**。**幕を足す人は、ここも一緒に見ること。**
 * 幕は `z-index` で上下が決まるが、**受け口の呼ばれる順は「窓へ登録した順」**で、
 * **上下とは一致しない**——身元を固定した（上）ことで、**順は「開いた順」になった**。
 *
 * 2026-09-08 に踏んだ形: **設定を開いてからカードを挿す**と、順が
 * 「設定 → ウィザード」になる。設定が自分で閉じると、**その場で描き直しが走って
 * ウィザードの `yieldEsc` が偽になり**、**同じ押しでウィザードまで閉じた**
 * （＝挿したカードの用が黙って消える）。
 *
 * **譲る側の判断（`yieldEsc`）と、これは別物である。** あちらは「誰が答えるか」、
 * こちらは「**二度答えない**」。**両方要る。**
 *
 * ## 限界——**これは「先に登録した側が勝つ」**
 *
 * 身元を固定した以上、**呼ばれる順は「開いた順」**である。**手前かどうかは見ていない。**
 * いま安全なのは、**幕が別の幕の下に生まれない**ように作ってあるからである:
 *
 * - 軽い幕（パレット・一覧・メニュー）は、**上に幕が立つと畳む／開かない**
 * - **関所と設定の手前では、取り込みのウィザードを開かず待たせる**（`App.tsx` の `openWizard`）
 *
 * **幕を1枚足す人へ**: **下に生まれる道を作らないこと。** 作るなら、
 * ここに `z-index` の順を持ち込む（いまは持っていない）。
 */
export function answerKey(e: KeyboardEvent): boolean {
  // **押しっぱなしの繰り返しは答えない**（2026-09-08）。`Esc` を押さえていると
  // **毎秒30回ほど届く**ので、**1打ごとに幕が1枚ずつ剥がれる**——
  // **押した人は1枚のつもりで、確認の面まで消える**。
  // **1回の物理の押しに、この道を通る幕は1つだけ答える。**
  if (e.repeat) return false;
  if (answered === e) return false;
  answered = e;
  // **配信が終わったら手放す。** `queueMicrotask` では**早すぎる**
  // ——マイクロタスクは**受け口と受け口の間で走る**ので、同じ押しの続きが
  // 「まだ誰も答えていない」と読んでしまう。`setTimeout` は次の仕事なので、
  // **その押しの配信が全部終わったあと**に落ちる
  window.setTimeout(() => {
    if (answered === e) answered = null;
  }, 0);
  return true;
}
